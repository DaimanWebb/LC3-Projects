;   OBJECTIVE:
;-------------------------------------------------------------------------
;   1. TESTING DATA MOVES INSTRUCTIONS
;==========================================================================
;                          HIGH-LEVEL BREAKDOWN    
;-------------------------------------------------------------------------
;   1. We can use a label OR hardcode the address
;   2. Load the address of the first number into R2
;==========================================================================
;                          REGISTER CONVENTION
;==========================================================================
;-------------------------------------------------------------------------
; R0    :   
; EOP   :   
;-------------------------------------------------------------------------
; R1    :   NUMBER TO BE ADDED
; EOP   :   #15
;-------------------------------------------------------------------------
; R2    :   PTR ADDRESS
; EOP   :   PTR ADDRESS
;-------------------------------------------------------------------------
; R3    :   LABEL ADDRESS
; EOP   :   LABEL ADDRESS
;-------------------------------------------------------------------------
; R4    :   ALIAS ADDRESS
; EOP   :   ALIAS ADDRESS
;-------------------------------------------------------------------------
; R5    :   PTR ADDRESS
; EOP   :   #5
;-------------------------------------------------------------------------
; R6    :   LABEL DATA
; EOP   :   #10
;-------------------------------------------------------------------------
; R7    :   ALIAS DATA
; EOP   :   #15
;-------------------------------------------------------------------------
;==========================================================================
.ORIG x3000 
;-------------------------------------------------------------------------
; STORE #5 AT ADDRESS ALIASED BY PTR  ——  STORE #5 AT x3000
;-------------------------------------------------------------------------
    AND R1, R1, #0      ;   CLEAR R1
    ADD R1, R1, #5      ;   R1 <— R1 + 5
    STI R1, PTR         ;   STORE 5 AT x3000
;-------------------------------------------------------------------------
; STORE #10 AT ADDRESS ALIASED BY LABEL  ——  STORE #10 AT x3010
;-------------------------------------------------------------------------
    ADD R1 R1 #5        ;   R1 <— R1 + 5
    STI R1 LABEL        ;   STORE #10 AT x3010
;-------------------------------------------------------------------------
; STORE #15 AT ADDRESS ALIASED BY ALIAS  ——  STORE #15 AT x3010
;-------------------------------------------------------------------------
    ADD R1 R1 #5        ;   R1 <— R1 + 5
    STI R1 ALIAS        ;   STORE #10 AT x3020
;-------------------------------------------------------------------------
; LOAD R5 - R7 WITH VALUES AT THE FOLLOWING MEMORY LOCATIONS: x3100, x3101, x3102
;-------------------------------------------------------------------------
    LDI R5 PTR          ;   LOAD INTO R5 DATA STORED AT ADDRESS STORED IN R2 (x3000)
    LDI R6 LABEL        ;   LOAD INTO R6 DATA STORED AT ADDRESS STORED IN R3 (x3010)
    LDI R7 ALIAS        ;   LOAD INTO R7 DATA STORED AT ADDRESS STORED IN R4 (x3020)
    HALT                ;   HALT PROGRAM
;-------------------------------------------------------------------------
; PSEUDO-OPS
;-------------------------------------------------------------------------
PTR     .FILL   x3100   ;   TEST ADDRESS TO STORE 5 
LABEL   .FILL   x3101   ;   HOLDS THE ADDRESS OF FIRST NUMBER TO ADD
ALIAS   .FILL   x3102   ;   TEST ADDRESS TO STORE 10 
        .END            ;   END ASSEMBLY
;-------------------------------------------------------------------------

